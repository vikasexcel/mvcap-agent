"""Builds the bundled snapshot and the seed SQL from seed_data.py + data/directory.json.

    uv run python scripts/build_data.py            # writes data/snapshot.json and data/seed.sql

The snapshot is the offline fallback the agent ships with. seed.sql is the initial import
for Supabase; copy it into a migration (see context.md, section 14.6).
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

import seed_data  # noqa: E402

from dataset import Dataset  # noqa: E402


def sql(value) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (dict, list)) and not (
        isinstance(value, list) and value and isinstance(value[0], str)
    ):
        return "'" + json.dumps(value).replace("'", "''") + "'::jsonb"
    if isinstance(value, list):
        return "array[" + ", ".join(sql(v) for v in value) + "]::text[]"
    return "'" + str(value).replace("'", "''") + "'"


def sql_jsonb(value) -> str:
    return (
        "'" + json.dumps(value).replace("'", "''") + "'::jsonb"
        if value is not None
        else "null"
    )


def insert(table: str, columns: list[str], rows: list[dict]) -> str:
    def cell(row: dict, column: str) -> str:
        if table == "settings" and column == "value":
            return sql_jsonb(row.get(column))
        return sql(row.get(column))

    values = ",\n".join(
        "  (" + ", ".join(cell(r, c) for c in columns) + ")" for r in rows
    )
    return f"insert into public.{table} ({', '.join(columns)}) values\n{values}\non conflict do nothing;\n"


def tables() -> dict[str, list[dict]]:
    directory = json.loads((ROOT / "data" / "directory.json").read_text())
    for i, row in enumerate(directory, start=1):
        row["id"] = i
        row["active"] = True
    keywords = [dict(r, active=True) for r in seed_data.KEYWORDS]
    branches = [dict(r, active=True) for r in seed_data.BRANCHES]
    status = [
        dict(r, id=i, active=r.get("active", True))
        for i, r in enumerate(seed_data.STATUS_UPDATES, start=1)
    ]
    settings = [
        {"key": k, "value": v, "notes": n} for k, (v, n) in seed_data.SETTINGS.items()
    ]
    return {
        "keywords": keywords,
        "keyword_branches": branches,
        "directory": directory,
        "status_updates": status,
        "settings": settings,
    }


def main() -> None:
    t = tables()
    ds = Dataset.from_tables(t)
    errors, warnings = ds.problems()
    for w in warnings:
        print("warning:", w)
    if errors:
        print("\n".join("ERROR: " + e for e in errors))
        sys.exit(1)

    (ROOT / "data" / "snapshot.json").write_text(json.dumps(t, indent=1) + "\n")

    kw_cols = [
        "keyword",
        "alias_of",
        "action",
        "message",
        "message_source",
        "question",
        "target_type",
        "target",
        "voicemail_note",
        "notes",
    ]
    br_cols = [
        "keyword",
        "answer",
        "action",
        "message",
        "message_source",
        "target_type",
        "target",
        "goto_keyword",
        "voicemail_note",
        "notes",
    ]
    dir_cols = [
        "last_name",
        "first_legal",
        "first_preferred",
        "title",
        "extension",
        "direct_phone",
        "internal_only",
        "notes",
    ]
    su_cols = ["update_date", "text", "applies_to", "active", "notes"]
    st_cols = ["key", "value", "notes"]
    # Alias rows reference their canonical row, so insert canonical keywords first.
    ordered = [r for r in t["keywords"] if r["action"] != "alias"] + [
        r for r in t["keywords"] if r["action"] == "alias"
    ]
    out = [
        "-- Initial import of the MVCAP answering-service data (generated by scripts/build_data.py)\n",
        insert("keywords", kw_cols, ordered),
        insert("keyword_branches", br_cols, t["keyword_branches"]),
        insert("directory", dir_cols, t["directory"]),
        insert("status_updates", su_cols, t["status_updates"]),
        insert("settings", st_cols, t["settings"]),
    ]
    (ROOT / "data" / "seed.sql").write_text("\n".join(out))
    print(
        f"ok: {len(t['keywords'])} keywords ({len(ds.canonical_keywords())} canonical), "
        f"{len(t['keyword_branches'])} branches, {len(t['directory'])} people, "
        f"{len(t['status_updates'])} status updates, {len(t['settings'])} settings; "
        f"{len(warnings)} warning(s)"
    )


if __name__ == "__main__":
    main()
